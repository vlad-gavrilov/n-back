test('audio preparation blocks language changes and existing errors translate', async ({ page }) => {
  let release!: () => void; const pending = new Promise<void>(resolve => { release = resolve })
  await page.route('**/audio/*.wav*', async route => { await pending; await route.abort() })
  await page.goto('/'); await page.getByRole('button', { name: 'Dual', exact: true }).click()
  await page.getByRole('button', { name: 'Begin session' }).click()
  await expect(page.getByRole('button', { name: 'Русский', exact: true })).toBeDisabled()
  release(); await expect(page.getByRole('alert')).toBeVisible()
  await page.getByRole('button', { name: 'Русский', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Не удалось включить звук')
  await page.getByRole('button', { name: 'Выбрать визуальный режим' }).click()
  await expect(page.getByRole('button', { name: 'Визуальный', exact: true })).toHaveAttribute('aria-pressed', 'true')
})
for (const blocked of [false,true]) test(`locale storage fallback (blocked=${blocked})`, async ({ page }) => {
  await page.addInitScript(blocked => {
    if (blocked) { Object.defineProperty(Storage.prototype,'getItem',{value:()=>{throw Error('blocked')}}); Object.defineProperty(Storage.prototype,'setItem',{value:()=>{throw Error('blocked')}}) }
    else localStorage.setItem('nback-locale','invalid')
  }, blocked)
  await page.goto('/'); await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  await page.getByRole('button', { name: 'Русский', exact: true }).click(); await expect(page.locator('html')).toHaveAttribute('lang','ru')
})
