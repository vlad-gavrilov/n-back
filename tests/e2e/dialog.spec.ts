import { expect, test } from '@playwright/test'

test('dialog padding and dragging out keep it open; backdrop and Escape restore focus', async ({ page }) => {
  await page.setViewportSize({ width: 430, height: 700 })
  await page.goto('/')
  const opener = page.getByRole('button', { name: 'Session settings' })
  const dialog = page.getByRole('dialog')
  await opener.click()
  await dialog.click({ position: { x: 8, y: 8 } })
  await expect(dialog).toBeVisible()
  const box = (await dialog.boundingBox())!
  await page.mouse.move(box.x + 8, box.y + 8)
  await page.mouse.down()
  await page.mouse.move(2, 2)
  await page.mouse.up()
  await expect(dialog).toBeVisible()
  await page.mouse.move(2, 2)
  await page.mouse.down()
  await page.mouse.move(box.x + 8, box.y + 8)
  await page.mouse.up()
  await expect(dialog).toBeVisible()
  await page.mouse.click(2, 2)
  await expect(dialog).toHaveCount(0)
  await expect(opener).toBeFocused()
  await opener.click()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(opener).toBeFocused()
})

test('dialog contains scrolling and restores page position and inline body styles', async ({ page }) => {
  await page.setViewportSize({ width: 430, height: 430 })
  await page.goto('/')
  await page.evaluate(() => { document.body.style.paddingRight = '3px'; document.body.style.overflow = 'visible' })
  const beforeStyles = await page.locator('body').getAttribute('style')
  const opener = page.getByRole('button', { name: 'How to play' })
  await opener.focus()
  await page.evaluate(() => scrollTo(0, 100))
  const before = await page.evaluate(() => ({ x: scrollX, y: scrollY, width: document.querySelector('.app-shell')!.getBoundingClientRect().width }))
  await opener.press('Enter')
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  const locked = await page.evaluate(() => ({ x: scrollX, y: scrollY, width: document.querySelector('.app-shell')!.getBoundingClientRect().width }))
  expect(locked.width).toBeCloseTo(before.width, 0)
  const box = (await dialog.boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.wheel(0, 1200)
  await expect.poll(() => dialog.evaluate(e => e.scrollTop)).toBeGreaterThan(0)
  await page.mouse.wheel(0, 1200)
  await page.waitForTimeout(150)
  expect(await page.evaluate(() => ({ x: scrollX, y: scrollY }))).toEqual({ x: locked.x, y: locked.y })
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(opener).toBeFocused()
  expect(await page.evaluate(() => ({ x: scrollX, y: scrollY }))).toEqual({ x: before.x, y: before.y })
  expect(await page.locator('body').getAttribute('style')).toBe(beforeStyles)
})

test('closing sound preparation falls back to the trainer heading without a later focus jump', async ({ page }) => {
  let release!: () => void
  const pending = new Promise<void>(resolve => { release = resolve })
  await page.route('**/audio/*.wav*', async route => { await pending; await route.abort() })
  await page.setViewportSize({ width: 430, height: 700 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Session settings' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'Dual', exact: true }).click()
  await dialog.getByRole('button', { name: 'Test sound', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Session settings' })).toBeDisabled()
  await dialog.getByRole('button', { name: 'Close dialog' }).click()
  const heading = page.getByRole('heading', { level: 1 })
  await expect(heading).toBeFocused()
  release()
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(heading).toBeFocused()
  await expect(page.getByRole('button', { name: 'Session settings' })).toBeEnabled()
})
